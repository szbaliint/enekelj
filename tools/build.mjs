// Felépíti a játék adatfájljait (js/data-hu.js, js/data-en.js):
// csak azokat a szavakat tartja meg, amelyek tényleg elhangzanak a playlist valamelyik dalában,
// és minden szóhoz eltárolja, mely dalokban szerepel. Maga a dalszöveg NEM kerül a repóba.
//
// Builds the game data files: keeps only words that actually occur in the lyrics of a playlist
// song, and records which songs contain each word. The lyrics themselves are NOT committed.
//
// Usage:
//   NODE_USE_ENV_PROXY=1 node tools/fetch-lyrics.mjs    # once, fills .cache/lyrics
//   NODE_USE_ENV_PROXY=1 node tools/fetch-youtube.mjs   # once, fills .cache/youtube
//   node tools/build.mjs
import { readFile, writeFile } from "node:fs/promises";
import vm from "node:vm";

vm.runInThisContext(await readFile("js/match.js", "utf8"));
const { textMatches } = globalThis.Match;

const PLAYLISTS = {
  hu: { name: "magyar chill pt2", url: "https://open.spotify.com/playlist/5QrmfO0XziaHFTL4wr8XNW" },
  en: { name: "random chill", url: "https://open.spotify.com/playlist/4Kcl4WIGu4h1YTqYN8midO" },
};
const LEVELS = ["konnyu", "kozepes", "nehez"];
const clean = (t) => t.replace(/\s*[([](feat\.|with |from )[^)\]]*[)\]]/gi, "").replace(/\s+-\s+.*remix.*$/i, "").trim();

for (const lang of Object.keys(PLAYLISTS)) {
  const tracks = JSON.parse(await readFile(`data/tracks-${lang}.json`, "utf8"));
  const candidates = JSON.parse(await readFile(`data/words-${lang}.json`, "utf8"));

  const songs = [];
  const lyrics = [];
  for (const tr of tracks) {
    let cached;
    try { cached = JSON.parse(await readFile(`.cache/lyrics/${lang}/${tr.id}.json`, "utf8")); } catch (_) { continue; }
    if (!cached.lrclib || !cached.lyrics) continue;
    // yt: YouTube-videó azonosító (ha van egyező hosszúságú); s: 1, ha van időzített dalszöveg
    // yt: YouTube video id (if a length-matched one exists); s: 1 if lrclib has synced lyrics
    let yt = {};
    try { yt = JSON.parse(await readFile(`.cache/youtube/${lang}/${tr.id}.json`, "utf8")); } catch (_) { /* run fetch-youtube */ }
    const song = { t: clean(tr.t), a: tr.a, id: tr.id, d: tr.d, lrc: cached.lrclib };
    if (yt.yt) song.yt = yt.yt;
    if (yt.synced) song.s = 1;
    songs.push(song);
    lyrics.push(cached.lyrics);
  }

  const words = {};
  const dropped = [];
  for (const level of LEVELS) {
    words[level] = [];
    for (const word of candidates[level]) {
      const hits = [];
      lyrics.forEach((text, i) => { if (textMatches(word, text, lang)) hits.push(i); });
      if (hits.length) words[level].push([word, hits]);
      else dropped.push(word);
    }
  }

  const data = { ...PLAYLISTS[lang], songs, words };
  const js = `// GENERÁLT FÁJL – ne szerkeszd kézzel. / GENERATED by tools/build.mjs – do not edit.\n` +
    `// words: [szó, [dalok indexei, amelyek szövegében elhangzik]] / [word, [indexes of songs whose lyrics contain it]]\n` +
    `window.GAME_DATA = window.GAME_DATA || {};\n` +
    `window.GAME_DATA.${lang} = ${JSON.stringify(data)};\n`;
  await writeFile(`js/data-${lang}.js`, js);

  const counts = LEVELS.map((l) => `${l} ${words[l].length}`).join(", ");
  const playable = songs.filter((x) => x.yt && x.s).length;
  console.log(`${lang}: ${songs.length}/${tracks.length} songs with lyrics; words: ${counts}`);
  console.log(`  YouTube: ${songs.filter((x) => x.yt).length}, synced lyrics: ${songs.filter((x) => x.s).length}, usable for "finish the lyrics": ${playable}`);
  console.log(`  dropped (not in any lyrics): ${dropped.join(", ")}`);
}
